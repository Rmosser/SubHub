let currentLocale: Locale = DEFAULT_LOCALE;

function normalizeLocale(value: string | null | undefined): Locale | "" {
  const text = String(value || "").trim();
  if (!text) return "";
  const normalized = text.toLowerCase();
  if (normalized === "zh" || normalized === "zh-cn" || normalized === "zh-hans") return "zh-CN";
  if (normalized === "en" || normalized === "en-us") return "en-US";
  return SUPPORTED_LOCALES.includes(text as Locale) ? (text as Locale) : "";
}

function getCookie(name: string): string {
  const parts = String(document.cookie || "").split(";");
  for (const part of parts) {
    const [rawKey, ...rest] = part.split("=");
    if (String(rawKey || "").trim() === name) {
      return decodeURIComponent(rest.join("="));
    }
  }
  return "";
}

function setCookie(name: string, value: string): void {
  const expires = new Date(Date.now() + 365 * 24 * 60 * 60 * 1000).toUTCString();
  document.cookie = `${name}=${encodeURIComponent(value)}; expires=${expires}; path=/; SameSite=Lax`;
}

export function getLocale(): Locale {
  return currentLocale;
}

export function isEnglish(): boolean {
  return currentLocale === "en-US";
}

export function t(key: string, vars: Record<string, string | number> = {}): string {
  const table = KEYED_TRANSLATIONS[currentLocale] || KEYED_TRANSLATIONS[DEFAULT_LOCALE];
  const template = table[key] || KEYED_TRANSLATIONS[DEFAULT_LOCALE][key] || key;
  return template.replace(/\{(\w+)\}/g, (_match, name) => String(vars[name] ?? ""));
}

export function tx(text: string): string {
  if (!text || currentLocale !== "en-US") return text;
  return EXACT_TRANSLATIONS[text.trim()] || text;
}

export function initLocale(): Locale {
  currentLocale =
    normalizeLocale(getCookie(COOKIE_NAME)) ||
    normalizeLocale(localStorage.getItem(COOKIE_NAME)) ||
    normalizeLocale(navigator?.language) ||
    DEFAULT_LOCALE;
  localStorage.setItem(COOKIE_NAME, currentLocale);
  setCookie(COOKIE_NAME, currentLocale);
  document.documentElement.lang = currentLocale;
  return currentLocale;
}

export function setLocale(locale: Locale): void {
  currentLocale = normalizeLocale(locale) as Locale || DEFAULT_LOCALE;
  localStorage.setItem(COOKIE_NAME, currentLocale);
  setCookie(COOKIE_NAME, currentLocale);
  window.location.reload();
}
