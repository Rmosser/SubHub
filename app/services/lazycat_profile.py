def _copy_setting_value(value: Any) -> Any:
    if isinstance(value, list):
        return list(value)
    if isinstance(value, dict):
        return dict(value)
    return value


def _should_backfill_legacy_mihomo_mainline_settings(
    raw: Mapping[str, object] | None,
) -> bool:
    payload = dict(raw) if isinstance(raw, Mapping) else {}
    enhanced_mode = str(payload.get(LAZYCAT_PROFILE_CLASH_DNS_ENHANCED_MODE_KEY, "") or "").strip()
    if enhanced_mode == "fake-ip":
        return True
    if enhanced_mode == "redir-host":
        return False
    if payload.get(LAZYCAT_PROFILE_CLASH_DNS_USE_HOSTS_KEY) is True:
        return False
    if payload.get(LAZYCAT_PROFILE_CLASH_TUN_ENABLE_KEY) is False:
        return False
